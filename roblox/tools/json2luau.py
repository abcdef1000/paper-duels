#!/usr/bin/env python3
"""Converts the website's question banks (docs/*.json) into src/server/Banks.luau.
Questions with a figure (the SVG diagrams don't exist in Roblox) and short-answer questions are skipped.
Run from the roblox/ folder:  python3 tools/json2luau.py"""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
DOCS = os.path.join(HERE, "..", "..", "docs")
OUT = os.path.join(HERE, "..", "src", "server", "Banks.luau")
# every subject registered in docs/packs.json
BANKS = [(p["key"], p["file"], p["name"]) for p in json.load(open(os.path.join(DOCS, "packs.json"), encoding="utf-8"))]

def s(v):
    return '"' + v.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'

lines = ["-- Generated by tools/json2luau.py from docs/*.json. Do not edit by hand; edit the JSON and re-run.",
         "-- Lives in ServerScriptService so clients can't read the answers.", "return {",
         "\torder = { " + ", ".join(s(k) for k, _, _ in BANKS) + " },"]
for key, fname, name in BANKS:
    data = json.load(open(os.path.join(DOCS, fname), encoding="utf-8"))
    qs = [q for q in data["questions"] if not q.get("fig") and not q.get("of") and q.get("type", "mcq") == "mcq"]
    lines.append(f"\t[{s(key)}] = {{")   # bracketed so keys like "o-phys" are valid Lua
    lines.append(f"\t\tname = {s(name)},")
    lines.append(f"\t\tconstants = {s(data.get('constants', ''))},")
    lines.append("\t\tquestions = {")
    for q in qs:
        opts = ", ".join(s(o) for o in q["o"])
        lines.append(f"\t\t\t{{ id = {s(q['id'])}, topic = {s(q['topic'])}, quick = {'true' if q.get('quick') else 'false'}, q = {s(q['q'])}, o = {{ {opts} }}, a = {q['a'] + 1}, x = {s(q['x'])} }},")
    lines.append("\t\t},")
    lines.append("\t},")
    print(f"{name}: {len(qs)} questions ({len(data['questions']) - len(qs)} with figures or short answers skipped)")
lines.append("}")
open(OUT, "w", encoding="utf-8").write("\n".join(lines) + "\n")
